def test_plans_round_trip_and_reject_bad_boxes(tmp_path):
    plan = Plan(doc="d", pdf="d.pdf", identity={"Paciente": "X Y, Z"})
    plan.boxes.append(Box(1, 0.1, 0.1, 0.3, 0.2, "Paciente", "hand"))
    save_plan(tmp_path, plan, pages=1)
    again = load_plan(tmp_path, "d")
    assert again == plan
    assert again.text_for(again.boxes[0]) == "X Y, Z"
    for bad in (
        Box(1, 0.3, 0.1, 0.2, 0.2, "Paciente"),
        Box(1, 0.1, 0.1, 0.2, 0.2, "Nombre"),
        Box(2, 0.1, 0.1, 0.2, 0.2, COVER),
    ):
        with pytest.raises(ValueError):
            Plan(doc="d", pdf="d.pdf", identity={}, boxes=[bad]).validate(pages=1)


