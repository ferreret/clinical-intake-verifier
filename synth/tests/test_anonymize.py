def _pdf_with_text(path: Path) -> None:
    doc = pymupdf.open()
    page = doc.new_page(width=595, height=842)
    page.insert_text((72, 100), SECRET, fontsize=14)
    page.insert_text((72, 300), "Hemograma, glucosa", fontsize=14)
    doc.set_metadata({"author": "Someone Real", "title": SECRET})
    doc.save(path)


def test_painting_leaves_an_image_only_pdf_without_the_original(tmp_path):
    src = tmp_path / "doc.pdf"
    _pdf_with_text(src)
    plan = Plan(doc="doc", pdf="doc.pdf", identity={"Paciente": "RUIZ PONS, ANA"})
    plan.boxes = [
        Box(1, 0.11, 0.095, 0.45, 0.125, "Paciente", "hand"),
        Box(1, 0.11, 0.33, 0.30, 0.36, COVER),
    ]
    truth = apply_plan(src, plan, tmp_path / "out.pdf")
    assert truth["fields"] == {"Paciente": "RUIZ PONS, ANA"}
    out = pymupdf.open(tmp_path / "out.pdf")
    assert out.page_count == 1
    assert out[0].get_text().strip() == ""
    assert SECRET not in json.dumps(out.metadata)
    assert abs(out[0].rect.width - 595) < 1.5 and abs(out[0].rect.height - 842) < 1.5
    page = render(tmp_path / "out.pdf", 1, 100).image.convert("L")
    w, h = page.size

    def ink(box):  # share of dark pixels in a region of the output
        px = list(
            page.crop(
                (int(box[0] * w), int(box[1] * h), int(box[2] * w), int(box[3] * h))
            ).get_flattened_data()
        )
        return sum(v < 128 for v in px) / len(px)

    assert ink((0.12, 0.10, 0.44, 0.12)) > 0.02  # the fictitious name was written
    assert ink((0.12, 0.335, 0.29, 0.355)) < 0.001  # the covered line is gone
    assert ink((0.12, 0.40, 0.9, 0.9)) == 0  # nothing else drawn


def test_a_value_written_in_parts_is_recorded_whole():
    plan = Plan(
        doc="d", pdf="d.pdf", identity={"Paciente": "ANA RUIZ PONS", "Telefono": "600111222"}
    )
    plan.boxes = [
        Box(1, 0.1, 0.10, 0.4, 0.12, "Paciente", "hand", text="RUIZ"),
        Box(1, 0.1, 0.13, 0.4, 0.15, "Paciente", "hand", text="PONS"),
        Box(1, 0.1, 0.16, 0.4, 0.18, "Paciente", "hand", text="ANA"),
        Box(2, 0.1, 0.10, 0.4, 0.12, "Paciente"),  # the whole value again, elsewhere
        Box(1, 0.5, 0.10, 0.8, 0.12, "Telefono", text="600 11 12 22"),
        Box(1, 0.5, 0.20, 0.8, 0.22, OTHER, text="C/ Mayor 3"),
        Box(1, 0.5, 0.30, 0.8, 0.32, COVER),
    ]
    assert plan.written() == {
        "Paciente": "ANA RUIZ PONS",
        "Telefono": "600 11 12 22",
        OTHER: "C/ Mayor 3",
    }
    plan.boxes[1].text = "P."  # not the identity's words: the first box's text, as before
    assert plan.written()["Paciente"] == "RUIZ"
    plan.boxes[0].text, plan.boxes[1].text = "Ruiz", "Pons,"  # case and commas aside
    assert plan.written()["Paciente"] == "ANA RUIZ PONS"
    plan.identity["Paciente"] = "RUIZ PONS, ANA"
    assert plan.written()["Paciente"] == "RUIZ PONS, ANA"


