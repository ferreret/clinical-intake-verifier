def _call(url, method="GET", body=None):
    req = urllib.request.Request(
        url, method=method, data=None if body is None else json.dumps(body).encode()
    )
    req.add_header("Content-Type", "application/json")
    try:
        with urllib.request.urlopen(req) as r:
            return r.status, r.read(), r.headers.get("Content-Type")
    except urllib.error.HTTPError as err:
        return err.code, err.read(), err.headers.get("Content-Type")


def test_the_review_server_saves_previews_and_applies(server):
    base, work = server
    status, _, ctype = _call(base + "/")
    assert status == 200 and ctype.startswith("text/html")
    docs = json.loads(_call(base + "/api/docs")[1])["docs"]
    assert [d["doc"] for d in docs] == ["doc-a"] and docs[0]["boxes"] == 0
    plan = json.loads(_call(base + "/api/doc/doc-a")[1])["plan"]
    plan["boxes"].append(
        {
            "page": 1,
            "x0": 0.11,
            "y0": 0.095,
            "x1": 0.45,
            "y1": 0.125,
            "kind": "Paciente",
            "style": "print",
            "text": None,
            "source": "manual",
        }
    )
    plan["reviewed"] = True
    assert _call(base + "/api/plan/doc-a", "PUT", plan)[0] == 200
    assert load_plan(work, "doc-a").reviewed
    status, png, ctype = _call(base + "/api/preview/doc-a/1.png", "POST", plan)
    assert status == 200 and ctype == "image/png" and Image.open(io.BytesIO(png)).size[0] > 100
    status, _, _ = _call(base + "/api/apply/doc-a", "POST")
    assert status == 200 and (work / "out" / "doc-a.pdf").exists()


def test_the_review_server_refuses_unknown_documents_and_bad_plans(server):
    base, _ = server
    assert _call(base + "/api/doc/..%2Fsecret")[0] == 404
    assert _call(base + "/api/page/doc-a/9.png")[0] == 404
    bad = {
        "doc": "doc-a",
        "pdf": "doc-a.pdf",
        "identity": {},
        "boxes": [{"page": 1, "x0": 0.5, "y0": 0.1, "x1": 0.2, "y1": 0.2, "kind": "Paciente"}],
    }
    assert _call(base + "/api/plan/doc-a", "PUT", bad)[0] == 400
    assert _call(base + "/api/plan/doc-a", "PUT", {**bad, "doc": "other", "boxes": []})[0] == 400
