SECRET = "SECRETO 12345678Z"


def _dni_ok(raw: str) -> bool:
    raw = re.sub(r"[^0-9A-Z]", "", raw.upper())
    if raw[0] in "XYZ":
        return DNI_LETTERS[int(f"{'XYZ'.index(raw[0])}{raw[1:8]}") % 23] == raw[8]
    return DNI_LETTERS[int(raw[:8]) % 23] == raw[8]


