"use client";

/**
 * A new batch: which model reads it, and its documents. The bundled synthetic requests in both
 * modes (in replay mode, those with a recorded reply for that model); uploaded PDFs too in
 * live mode, in the same batch if wanted.
 */
import Link from "next/link";
import { useRouter } from "next/navigation";
import { useEffect, useMemo, useState } from "react";

import { api, PROVIDER_LABEL, type BundledInfo, type Provider } from "../../_ui/api";
import { useSession } from "../../_ui/session";

const MAX_DOCUMENTS = 50;
const RANDOM_SIZE = 5;

const LANGUAGE: Record<string, string> = { es: "Spanish", ca: "Catalan" };

export default function NewBatchPage() {
  const { mode } = useSession();
  const router = useRouter();
  const [provider, setProvider] = useState<Provider>("gemini");
  const [name, setName] = useState("");
  const [bundled, setBundled] = useState<BundledInfo[] | null>(null);
  const [selected, setSelected] = useState<Set<string>>(new Set());
  const [files, setFiles] = useState<File[]>([]);
  const [filter, setFilter] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    let current = true;
    api.bundled(provider).then(
      (r) => {
        if (!current) return;
        setBundled(r.documents);
        const available = new Set(r.documents.map((d) => d.name));
        setSelected((s) => new Set([...s].filter((n) => available.has(n))));
      },
      (e: Error) => setError(e.message),
    );
    return () => {
      current = false;
    };
  }, [provider]);

  const shown = useMemo(
    () => (bundled ?? []).filter((d) => d.name.toLowerCase().includes(filter.trim().toLowerCase())),
    [bundled, filter],
  );
  const count = selected.size + files.length;

  function chooseProvider(p: Provider) {
    setProvider(p);
    setBundled(null);
  }

  function toggle(n: string) {
    setSelected((s) => {
      const next = new Set(s);
      if (next.has(n)) next.delete(n);
      else next.add(n);
      return next;
    });
  }

  function pickRandom() {
    const pool = shown.filter((d) => !selected.has(d.name));
    const next = new Set(selected);
    while (next.size < selected.size + RANDOM_SIZE && pool.length > 0 && next.size + files.length < MAX_DOCUMENTS) {
      next.add(pool.splice(Math.floor(Math.random() * pool.length), 1)[0].name);
    }
    setSelected(next);
  }

  async function create() {
    setBusy(true);
    setError(null);
    try {
      const { batch } = await api.createBatch({ provider, name, documents: [...selected].sort(), files });
      router.push(`/batches/${batch.id}`);
    } catch (e) {
      setError((e as Error).message);
      setBusy(false);
    }
  }

  return (
    <>
      <Link href="/batches" className="text-sm text-neutral-500 hover:underline">
        ← Batches
      </Link>
      <h1 className="mt-2 text-xl font-semibold tracking-tight">New batch</h1>

      <section className="mt-6 grid gap-6 sm:grid-cols-2">
        <label className="block">
          <span className="text-sm font-medium">Name</span>
          <input
            value={name}
            onChange={(e) => setName(e.target.value)}
            placeholder="Optional, e.g. Morning post"
            maxLength={100}
            className="mt-1.5 w-full rounded-md border border-neutral-300 px-3 py-2 text-sm focus:border-neutral-500 focus:outline-none"
          />
        </label>
        <fieldset>
          <legend className="text-sm font-medium">Read by</legend>
          <div className="mt-1.5 flex gap-2">
            {(Object.keys(PROVIDER_LABEL) as Provider[]).map((p) => (
              <label
                key={p}
                className={`flex-1 cursor-pointer rounded-md border px-3 py-2 text-sm ${
                  provider === p ? "border-neutral-900 bg-neutral-50" : "border-neutral-300"
                }`}
              >
                <input type="radio" name="provider" value={p} checked={provider === p} onChange={() => chooseProvider(p)} className="sr-only" />
                {PROVIDER_LABEL[p]}
              </label>
            ))}
          </div>
        </fieldset>
      </section>

      <section className="mt-8">
        <div className="flex flex-wrap items-end gap-3">
          <div className="mr-auto">
            <h2 className="text-sm font-medium">Synthetic requests</h2>
            <p className="text-xs text-neutral-500">
              {mode === "replay"
                ? `Those with a recorded reply from ${PROVIDER_LABEL[provider]}.`
                : "Generated by the project, with their ground truth."}
            </p>
          </div>
          <input
            value={filter}
            onChange={(e) => setFilter(e.target.value)}
            placeholder="Filter by name"
            className="w-40 rounded-md border border-neutral-300 px-2.5 py-1.5 text-sm focus:border-neutral-500 focus:outline-none"
          />
          <button type="button" onClick={pickRandom} className="rounded-md border border-neutral-300 px-2.5 py-1.5 text-sm hover:bg-neutral-50">
            Add {RANDOM_SIZE} at random
          </button>
          <button
            type="button"
            onClick={() => setSelected(new Set())}
            disabled={selected.size === 0}
            className="rounded-md border border-neutral-300 px-2.5 py-1.5 text-sm hover:bg-neutral-50 disabled:opacity-40"
          >
            Clear
          </button>
        </div>

        <div className="mt-3 max-h-80 overflow-y-auto rounded-lg border border-neutral-200">
          <table className="w-full text-sm">
            <thead className="sticky top-0 bg-neutral-50 text-left text-xs text-neutral-500">
              <tr>
                <th className="w-10 px-3 py-2" />
                <th className="px-3 py-2 font-medium">Document</th>
                <th className="px-3 py-2 font-medium">Pages</th>
                <th className="hidden px-3 py-2 font-medium sm:table-cell">Kind</th>
                <th className="hidden px-3 py-2 font-medium sm:table-cell">Language</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-neutral-100">
              {bundled === null && (
                <tr>
                  <td colSpan={5} className="px-3 py-6 text-center text-neutral-500">
                    Loading…
                  </td>
                </tr>
              )}
              {shown.map((d) => (
                <tr key={d.name} onClick={() => toggle(d.name)} className="cursor-pointer hover:bg-neutral-50">
                  <td className="px-3 py-1.5">
                    <input
                      type="checkbox"
                      checked={selected.has(d.name)}
                      onChange={() => toggle(d.name)}
                      onClick={(e) => e.stopPropagation()}
                      aria-label={`Include ${d.name}`}
                    />
                  </td>
                  <td className="px-3 py-1.5 font-mono text-xs">{d.name}</td>
                  <td className="px-3 py-1.5 tabular-nums">{d.pages ?? "–"}</td>
                  <td className="hidden px-3 py-1.5 text-neutral-600 sm:table-cell">
                    {[d.scanned ? "scanned" : d.scanned === false ? "digital" : null, d.handwritten ? "handwriting" : null]
                      .filter(Boolean)
                      .join(", ") || "–"}
                  </td>
                  <td className="hidden px-3 py-1.5 text-neutral-600 sm:table-cell">{LANGUAGE[d.language ?? ""] ?? "–"}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </section>

      {mode === "live" && (
        <section className="mt-8">
          <h2 className="text-sm font-medium">Your PDFs</h2>
          <p className="text-xs text-neutral-500">Kept on this machine, outside the repository. Read by the model you chose above.</p>
          <input
            type="file"
            accept="application/pdf"
            multiple
            onChange={(e) => setFiles([...files, ...Array.from(e.target.files ?? [])])}
            className="mt-2 block text-sm"
          />
          {files.length > 0 && (
            <ul className="mt-2 space-y-1 text-sm">
              {files.map((f, i) => (
                <li key={`${f.name}-${i}`} className="flex items-center gap-3">
                  <span className="font-mono text-xs">{f.name}</span>
                  <button type="button" onClick={() => setFiles(files.filter((_, j) => j !== i))} className="text-xs text-neutral-500 hover:underline">
                    remove
                  </button>
                </li>
              ))}
            </ul>
          )}
        </section>
      )}

      <div className="sticky bottom-0 mt-8 flex items-center gap-4 border-t border-neutral-200 bg-white py-4">
        <span className="text-sm text-neutral-600">
          {count} document{count === 1 ? "" : "s"}
          {count > MAX_DOCUMENTS && <span className="text-rose-700"> (at most {MAX_DOCUMENTS})</span>}
        </span>
        {error && <span className="text-sm text-rose-700">{error}</span>}
        <button
          type="button"
          onClick={create}
          disabled={busy || count === 0 || count > MAX_DOCUMENTS}
          className="ml-auto rounded-md bg-neutral-900 px-4 py-2 text-sm font-medium text-white hover:bg-neutral-700 disabled:opacity-40"
        >
          {busy ? "Creating…" : "Create and read"}
        </button>
      </div>
    </>
  );
}
